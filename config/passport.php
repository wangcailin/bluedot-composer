<?php

return [

    /*
    |--------------------------------------------------------------------------
    | Passport Guard
    |--------------------------------------------------------------------------
    |
    | 指定 Passport 使用的认证守卫。该值应该对应于你的 "auth" 配置文件中
    | 已经存在的守卫之一。
    |
    */

    'guard' => env('PASSPORT_GUARD', 'web'),

    /*
    |--------------------------------------------------------------------------
    | Passport 路径前缀
    |--------------------------------------------------------------------------
    |
    | Passport 路由的 URL 前缀。默认为 'oauth'。
    |
    */

    'path' => env('PASSPORT_PATH', 'oauth'),

    /*
    |--------------------------------------------------------------------------
    | 加密密钥
    |--------------------------------------------------------------------------
    |
    | Passport 在生成安全访问令牌时使用加密密钥。默认情况下，密钥存储为
    | 本地文件，但也可以通过环境变量设置，这样更方便。
    |
    */

    'private_key' => env('PASSPORT_PRIVATE_KEY'),

    'public_key' => env('PASSPORT_PUBLIC_KEY'),

    /*
    |--------------------------------------------------------------------------
    | 密钥存储路径（可选）
    |--------------------------------------------------------------------------
    |
    | 如果不使用环境变量存储密钥，可以指定密钥文件的存储路径。
    | 留空则使用 Laravel 默认的 storage_path()。
    |
    */

    'key_path' => env('PASSPORT_KEY_PATH'),

    /*
    |--------------------------------------------------------------------------
    | Passport 数据库连接
    |--------------------------------------------------------------------------
    |
    | 默认情况下，Passport 的模型将使用应用程序的默认数据库连接。
    | 如果你希望使用不同的连接，可以在此指定已配置的数据库连接名称。
    |
    */

    'connection' => env('PASSPORT_CONNECTION'),

];
